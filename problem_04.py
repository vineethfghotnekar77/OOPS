class calculator:
    def __init__(self , n):
        self.n = n
    def greet():
        print("Hello! Welcome to the calculator.")

calculator.greet()
c = calculator(int(input("Enter a number:")))

print("Square of the number is =",c.n**2)
print("Square root of the number is =",c.n**(1/2))
print("Cube of the number is =",c.n**3)